def _fmt(value: float, whole_fjd: bool = False) -> str:
    amount = float(value or 0)
    if whole_fjd:
        rounded = Decimal(str(amount)).quantize(Decimal("1"), rounding=ROUND_HALF_UP)
        return f"{rounded:,.0f}"
    return f"{amount:,.2f}"


def _whole_display(option: dict) -> bool:
    mode = option.get("amount_display")
    if mode in {"whole", "decimal"}:
        return mode == "whole"
    # Preserve the earlier behaviour when opening quotations generated by v1.6.
    return str(option.get("product", "")) == "PayGlobal"


def _paragraph(text: str, style: ParagraphStyle) -> Paragraph:
    safe = escape(str(text or "")).replace("\n", "<br/>")
    return Paragraph(safe, style)


def _option_lines_table(option: dict, styles: dict) -> tuple[Table, float]:
    item_rows = [["No.", "Description Of Items", "Qty", "Unit VIP FJD", "Total VIP FJD"]]
    lines = option.get("lines", []) or []
    whole_fjd = _whole_display(option)
    for idx, line in enumerate(lines, start=1):
        desc = str(line.get("description", ""))
        billing = str(line.get("billing", ""))
        qty = line.get("qty", 1)
        unit = float(line.get("unit_vip", 0) or 0)
        total = float(line.get("total_vip", unit * float(qty or 0)) or 0)

        # PayGlobal prices are displayed in whole FJD on the customer quote, matching
        # the source workbook's zero-decimal amount display. For annual recurring
        # bundles (where the internal quantity is 12 months), quote the annual package
        # as one line item so the displayed quantity × unit price equals the total.
        # Likewise, bundle one-time per-employee/per-user licences as one quoted line,
        # retaining the covered count in the description.
        if whole_fjd:
            qty_num = float(qty or 0)
            if billing.lower().startswith("annual") and qty_num == 12 and "recurring annually" in desc.lower():
                qty, unit = 1, total
            elif qty_num > 1 and billing.lower().startswith("one") and ("per employee" in desc.lower() or "per user" in desc.lower()):
                if not any(token in desc.lower() for token in (" employees)", " users)", " units)")):
                    covered = "employees" if "per employee" in desc.lower() else "users"
                    desc = f"{desc} ({qty_num:g} {covered})"
                qty, unit = 1, total

        # Avoid repeating the billing description when the main description already
        # communicates the recurring term.
        billing_already_shown = billing.lower() in desc.lower() or (
            billing.lower().startswith("annual") and "recurring annually" in desc.lower()
        )
        if billing and not billing_already_shown and billing not in ("One-time", ""):
            desc = f"{desc}\n{billing}"
        item_rows.append([
            str(idx), _paragraph(desc, styles["TableBody"]),
            f"{float(qty):g}" if isinstance(qty, (float, int)) else str(qty),
            _fmt(unit, whole_fjd), _fmt(total, whole_fjd),
        ])
    total_value = float(option.get("grand_total", option.get("subtotal", 0)) or 0)
    item_rows.append(["", Paragraph("<b>Grand Total</b>", styles["TableBodyBold"]), "", "", _fmt(total_value, whole_fjd)])
    table = Table(item_rows, colWidths=[10 * mm, 91 * mm, 15 * mm, 28 * mm, 31 * mm], repeatRows=1, hAlign="LEFT")
    table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), BLUE), ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"), ("FONTSIZE", (0, 0), (-1, 0), 8),
        ("ALIGN", (0, 0), (0, -1), "CENTER"), ("ALIGN", (2, 1), (-1, -1), "RIGHT"),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"), ("GRID", (0, 0), (-1, -2), 0.4, BORDER),
        ("BACKGROUND", (0, 1), (-1, -2), colors.white),
        ("BACKGROUND", (0, -1), (-1, -1), ORANGE), ("LINEABOVE", (0, -1), (-1, -1), 0.8, NAVY),
        ("FONTNAME", (0, -1), (-1, -1), "Helvetica-Bold"), ("FONTSIZE", (0, -1), (-1, -1), 9),
        ("LEFTPADDING", (0, 0), (-1, -1), 5), ("RIGHTPADDING", (0, 0), (-1, -1), 5),
        ("TOPPADDING", (0, 0), (-1, -1), 5), ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
    ]))
    return table, total_value



def _money(value: float, whole_fjd: bool = False) -> str:
    amount = float(value or 0)
    return f"$ {_fmt(amount, whole_fjd)}"


def _is_service_line(line: dict) -> bool:
    desc = str(line.get("description", "")).lower()
    method = str(line.get("pricing_method", "")).lower()
    return (
        "payglobal services worksheet" in method
        or desc.startswith("implementation services -")
        or desc.startswith("implementation, setup")
        or "service module" in str(line.get("row_type", "")).lower()
    )


def _payglobal_section_title(option: dict) -> str:
    variant = str(option.get("variant", "")).strip().lower().replace("-", " ")
    if "cloud" in variant and "hybrid" not in variant:
        return "PayGlobal Cloud Licenses and Setup"
    if "hybrid" in variant:
        return "PayGlobal Hybrid Subscription and Platform"
    if "on prem" in variant or "onprem" in variant:
        return "PayGlobal On-Premise Licenses and Setup"
    return f"PayGlobal {str(option.get('variant', '')).strip()} Licenses and Setup".strip()


def _friendly_line_description(line: dict) -> str:
    desc = str(line.get("description", "")).strip()
    # Remove internal costing annotations which belong in the verification workbook.
    desc = re.sub(r"\s*\(\s*\d+(?:\.\d+)?\s+units?;\s*recurring\s+(?:annually|quarterly)\s*\)\s*$", "", desc, flags=re.I)
    desc = re.sub(r"\s*-\s*per\s+(?:employee|user)\s*/\s*month\s*$", "", desc, flags=re.I)
    desc = re.sub(r"\s*-\s*per\s+month\s*$", "", desc, flags=re.I)
    desc = re.sub(r"\s*-\s*one-time\s*$", "", desc, flags=re.I)
    return desc.strip()


def _employee_count(lines: list[dict]) -> int | None:
    for line in lines:
        desc = str(line.get("description", ""))
        if not any(term in desc.lower() for term in ("payroll", "payroll / hr", "payroll/hr")):
            continue
        match = re.search(r"\((\d+(?:\.\d+)?)\s+units?;\s*recurring", desc, flags=re.I)
        if match:
            try:
                return int(float(match.group(1)))
            except ValueError:
                pass
        match = re.search(r"\((\d+)\s+employees?\)", desc, flags=re.I)
        if match:
            return int(match.group(1))
    return None


def _payglobal_quote_table(option: dict, styles: dict) -> tuple[Table, float]:
    """A PayGlobal customer quote table matching the attached commercial layout.

    Licence pricing is grouped into one-time setup and annual subscriptions for Cloud;
    services remain a separate line with their own detail and subtotal.
    """
    whole_fjd = _whole_display(option)
    all_lines = list(option.get("lines", []) or [])
    service_lines = [line for line in all_lines if _is_service_line(line)]
    licence_lines = [line for line in all_lines if not _is_service_line(line)]

    # Some older saved quotes may have services only in the detailed breakdown, not in
    # option.lines. Prefer that independent services calculation where it is available.
    service_records = list(option.get("services_breakdown", []) or [])
    service_total = float(option.get("services_total", 0) or 0)
    if service_total <= 0 and service_records:
        service_total = sum(float(item.get("total_services_cost", 0) or 0) for item in service_records)
    if service_total <= 0 and service_lines:
        service_total = sum(float(line.get("total_vip", 0) or 0) for line in service_lines)

    # Group recurring PayGlobal Cloud subscription components into a single annual
    # package line with the components listed underneath, as in the supplied example.
    variant = str(option.get("variant", "")).strip().lower().replace("-", " ")
    is_cloud = "cloud" in variant and "hybrid" not in variant
    display_lines: list[dict] = []
    recurring_sum = 0.0
    recurring_components: list[str] = []
    employee_count = _employee_count(licence_lines)

    if is_cloud:
        setup_lines = []
        recurring_lines = []
        other_lines = []
        assurance_lines = []
        for line in licence_lines:
            desc = str(line.get("description", "")).lower()
            billing = str(line.get("billing", "")).lower()
            if desc.strip() == "assurance" or desc.startswith("assurance "):
                assurance_lines.append(line)
            elif "setup" in desc or "configuration" in desc:
                setup_lines.append(line)
            elif "recurring" in billing or "recurring" in desc or billing.startswith("annual") or billing.startswith("quarter"):
                recurring_lines.append(line)
            else:
                other_lines.append(line)

        for line in setup_lines:
            amount = float(line.get("total_vip", 0) or 0)
            desc = _friendly_line_description(line)
            if "cloud" in variant:
                desc = "Cloud Environment and Setup Fees (one time cost)"
            display_lines.append({"description": desc, "qty": 1, "unit": amount, "total": amount})

        if recurring_lines:
            recurring_sum = sum(float(line.get("total_vip", 0) or 0) for line in recurring_lines)
            recurring_components = [_friendly_line_description(line) for line in recurring_lines]
            recurring_components = [d for d in recurring_components if d]
            if employee_count is not None:
                main_desc = f"PayGlobal Employees - Payroll ({employee_count} Employees) (Recurring Annually)"
            else:
                main_desc = "PayGlobal Cloud Subscription (Recurring Annually)"
            display_lines.append({
                "description": main_desc,
                "components": recurring_components,
                "qty": 1,
                "unit": recurring_sum,
                "total": recurring_sum,
                "recurring": True,
            })

        for line in other_lines + assurance_lines:
            amount = float(line.get("total_vip", 0) or 0)
            display_lines.append({"description": "Assurance" if str(line.get("description", "")).strip().lower().startswith("assurance") else _friendly_line_description(line),
                                  "qty": 1 if str(line.get("description", "")).strip().lower().startswith("assurance") else line.get("qty", 1),
                                  "unit": amount if str(line.get("description", "")).strip().lower().startswith("assurance") else float(line.get("unit_vip", amount) or amount),
                                  "total": amount})
    else:
        for line in licence_lines:
            amount = float(line.get("total_vip", 0) or 0)
            desc_raw = str(line.get("description", "")).strip()
            is_assurance = desc_raw.lower().startswith("assurance")
            desc = "Assurance" if is_assurance else _friendly_line_description(line)
            if line.get("billing") and not is_assurance and not any(t in desc.lower() for t in ("recurring annually", "recurring quarterly")):
                billing = str(line.get("billing", "")).strip()
                if billing.lower().startswith("annual") and "recurring" not in desc.lower():
                    desc = f"{desc} (Recurring Annually)"
            qty = 1 if is_assurance else line.get("qty", 1)
            unit = amount if is_assurance else float(line.get("unit_vip", amount) or amount)
            display_lines.append({"description": desc, "qty": qty, "unit": unit, "total": amount})

    # Calculate the licence subtotal from the underlying licence items. Display totals
    # retain the app's approved precision policy; the PDF merely changes presentation.
    licence_total = sum(float(line.get("total_vip", 0) or 0) for line in licence_lines)
    if not licence_lines and not service_lines:
        licence_total = float(option.get("grand_total", 0) or 0) - service_total

    headers = ["S/No.", "Description", "Qty", "Unit VIP FJD", "Total VIP FJD"]
    rows: list[list] = [headers]
    row_kinds: list[str] = ["header"]
    rows.append([_paragraph(_payglobal_section_title(option), styles["PayGlobalSection"]), "", "", "", ""])
    row_kinds.append("section")

    row_no = 1
    for item in display_lines:
        desc = escape(str(item.get("description", "")))
        components = item.get("components") or []
        if components:
            # Avoid repeating the primary Payroll/HR label as a sub-bullet; the parent
            # label already describes the employee subscription bundle.
            rendered_components = []
            for component in components:
                low = component.lower()
                if "payroll / hr" in low or low.startswith("payroll/hr") or low.startswith("payglobal employees - payroll"):
                    continue
                component = re.sub(r"\s*\(.*?\)\s*$", "", component).strip()
                if component:
                    rendered_components.append("&#8226;&nbsp; " + escape(component))
            if rendered_components:
                desc += "<br/>" + "<br/>".join(rendered_components)
        description = Paragraph(desc, styles["PayGlobalDescription"])
        qty_val = float(item.get("qty", 1) or 1)
        qty_text = f"{qty_val:g}"
        rows.append([
            str(row_no), description, qty_text,
            _money(float(item.get("unit", 0) or 0), whole_fjd=whole_fjd),
            _money(float(item.get("total", 0) or 0), whole_fjd=whole_fjd),
        ])
        row_kinds.append("item")
        row_no += 1

    has_services = service_total > 0
    if has_services:
        rows.append([_paragraph("Total Setup, License & Annual Assurance Cost", styles["PayGlobalTotalLabel"]), "", "", "", _money(licence_total, whole_fjd=whole_fjd)])
        row_kinds.append("subtotal")
        rows.append([_paragraph("Services - Implementation, Setup & Training", styles["PayGlobalSection"]), "", "", "", ""])
        row_kinds.append("section")
        activities = [
            "Scope/Workshops", "Build Payroll", "Build ESS", "Reporting (SSRS)",
            "Build Interfaces/Integration (Scope further)", "Payroll Consultant Testing QA",
            "Training", "User-Acceptance Testing Support", "Data Capture/Migration",
            "Parallel Run 1", "Parallel Run 2", "Go Live", "Post Go-Live Support", "Project Management",
        ]

        # Build ESS is a scope-specific deliverable, not a standard bullet. Include it
        # only when both (a) an ESS licence/subscription is selected in the quote and
        # (b) the separate services costing shows actual ESS implementation effort.
        # Older saved quotations without module-level services data retain backwards
        # compatibility, but still require an ESS product line.
        ess_product_included = any(
            re.search(r"\bess\b|employee\s+self\s+service", str(line.get("description", "")), re.I)
            and (float(line.get("qty", 0) or 0) > 0 or float(line.get("total_vip", 0) or 0) > 0)
            for line in licence_lines
        )
        ess_service_included = not service_records or any(
            str(record.get("module", "")).strip().lower() in {"ess", "employee self service", "employee self-service"}
            and (float(record.get("total_hours", 0) or 0) > 0 or float(record.get("total_services_cost", 0) or 0) > 0)
            for record in service_records
        )
        if not (ess_product_included and ess_service_included):
            activities = [activity for activity in activities if activity != "Build ESS"]

        bullets = "<br/>".join("&#8226;&nbsp; " + escape(activity) for activity in activities)
        service_desc = Paragraph(bullets, styles["PayGlobalServices"])
        rows.append(["2", service_desc, "1", "", _money(service_total, whole_fjd=whole_fjd)])
        row_kinds.append("service")
        rows.append([_paragraph("Sub Total - Services", styles["PayGlobalTotalLabel"]), "", "", "", _money(service_total, whole_fjd=whole_fjd)])
        row_kinds.append("subtotal")

    # The visible grand total reconciles the item/service figures shown on the quote.
    # Use the calculated option total when no services breakdown is attached.
    grand_total = float(option.get("grand_total", licence_total + service_total) or 0)
    rows.append([_paragraph("Grand Total", styles["PayGlobalGrandLabel"]), "", "", "", _money(grand_total, whole_fjd=whole_fjd)])
    row_kinds.append("grand")

    table = Table(rows, colWidths=[12 * mm, 91 * mm, 15 * mm, 28 * mm, 34 * mm], repeatRows=1, hAlign="LEFT")
    commands = [
        ("BACKGROUND", (0, 0), (-1, 0), NAVY),
        ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
        ("FONTSIZE", (0, 0), (-1, 0), 8),
        ("ALIGN", (0, 0), (0, -1), "CENTER"),
        ("ALIGN", (2, 1), (-1, -1), "RIGHT"),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("GRID", (0, 0), (-1, -1), 0.45, colors.HexColor("#111111")),
        ("LEFTPADDING", (0, 0), (-1, -1), 4),
        ("RIGHTPADDING", (0, 0), (-1, -1), 4),
        ("TOPPADDING", (0, 0), (-1, -1), 4),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
    ]
    for r, kind in enumerate(row_kinds):
        if kind == "section":
            commands.extend([
                ("SPAN", (0, r), (-1, r)),
                ("BACKGROUND", (0, r), (-1, r), SECTION_BLUE),
                ("TEXTCOLOR", (0, r), (-1, r), colors.white),
                ("FONTNAME", (0, r), (-1, r), "Helvetica-Bold"),
                ("ALIGN", (0, r), (-1, r), "LEFT"),
                ("TOPPADDING", (0, r), (-1, r), 6),
                ("BOTTOMPADDING", (0, r), (-1, r), 6),
            ])
        elif kind == "subtotal":
            commands.extend([
                ("SPAN", (0, r), (3, r)),
                ("BACKGROUND", (0, r), (-1, r), BEIGE),
                ("FONTNAME", (0, r), (-1, r), "Helvetica-Bold"),
                ("TEXTCOLOR", (0, r), (-1, r), colors.HexColor("#111111")),
                ("ALIGN", (4, r), (4, r), "RIGHT"),
            ])
        elif kind == "grand":
            commands.extend([
                ("SPAN", (0, r), (3, r)),
                ("BACKGROUND", (0, r), (-1, r), TOTAL_BLACK),
                ("TEXTCOLOR", (0, r), (-1, r), colors.white),
                ("FONTNAME", (0, r), (-1, r), "Helvetica-Bold"),
                ("FONTSIZE", (0, r), (-1, r), 10),
                ("TOPPADDING", (0, r), (-1, r), 6),
                ("BOTTOMPADDING", (0, r), (-1, r), 6),
            ])
        elif kind == "service":
            commands.extend([
                ("VALIGN", (0, r), (-1, r), "TOP"),
                ("TOPPADDING", (0, r), (-1, r), 5),
                ("BOTTOMPADDING", (0, r), (-1, r), 5),
            ])
    table.setStyle(TableStyle(commands))
    return table, float(option.get("grand_total", licence_total + service_total) or 0)


def _payglobal_recurring_note(option: dict, styles: dict) -> Table | None:
    variant = str(option.get("variant", "")).lower()
    if "cloud" not in variant or "hybrid" in variant:
        return None
    total = 0.0
    for line in option.get("lines", []) or []:
        if _is_service_line(line):
            continue
        desc = str(line.get("description", "")).lower()
        billing = str(line.get("billing", "")).lower()
        if "recurring" in billing or "recurring" in desc or billing.startswith("annual") or billing.startswith("quarter"):
            if not desc.startswith("assurance"):
                total += float(line.get("total_vip", 0) or 0)
    if total <= 0:
        return None
    note = Paragraph(
        f"<b><i>Note: Recurring Fees - {_money(total, whole_fjd=_whole_display(option))} / Year will be billed annually for On-Cloud Solution</i></b>",
        styles["PayGlobalRecurringNote"],
    )
    table = Table([[note]], colWidths=[180 * mm], hAlign="LEFT")
    table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), HIGHLIGHT_YELLOW),
        ("BOX", (0, 0), (-1, -1), 0, HIGHLIGHT_YELLOW),
        ("LEFTPADDING", (0, 0), (-1, -1), 2),
        ("RIGHTPADDING", (0, 0), (-1, -1), 2),
        ("TOPPADDING", (0, 0), (-1, -1), 4),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
    ]))
    return table

